const COMPATIBILITY_MAP = {
  'O-': ['O-', 'O+', 'A-', 'A+', 'B-', 'B+', 'AB-', 'AB+'],
  'O+': ['O+', 'A+', 'B+', 'AB+'],
  'A-': ['A-', 'A+', 'AB-', 'AB+'],
  'A+': ['A+', 'AB+'],
  'B-': ['B-', 'B+', 'AB-', 'AB+'],
  'B+': ['B+', 'AB+'],
  'AB-': ['AB-', 'AB+'],
  'AB+': ['AB+'],
};

export function canDonateTo(donorType, recipientType) {
  return COMPATIBILITY_MAP[donorType]?.includes(recipientType) ?? false;
}

export function getCompatibleRecipients(donorType) {
  return COMPATIBILITY_MAP[donorType] || [];
}
