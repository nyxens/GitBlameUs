import bcrypt from 'bcrypt';
import crypto from 'crypto';
import fs from 'fs';
import { connectDB } from './config/db.js';
import { Admin, Hospital, BloodBank, Staff, User } from './models/index.js';

/**
 * Creates 1 organization admin + 2 staff for every hospital and blood bank that has none yet,
 * and writes the generated credentials to <repo root>/CREDENTIALS.md.
 * Existing accounts are never touched (their passwords are unknown, only hashes are stored).
 */
const SALT_ROUNDS = 12;
const password = () => `Lv-${crypto.randomBytes(9).toString('base64url')}`;
const OUT = new URL('../CREDENTIALS.md', import.meta.url);

async function createAccount({ org, orgType, code, label, role, department, creator }) {
  const email = `${code}.${label}@lifevault.org`;
  if (await User.exists({ email })) return null;
  const plain = password();
  const user = await User.create({
    username: `${code}.${label}`,
    email,
    password: await bcrypt.hash(plain, SALT_ROUNDS),
    DOB: new Date('1990-01-01'),
    pincode: org.pincode,
    bloodgroup: 'O+',
    gender: 'OTHER',
    name: `${label.startsWith('admin') ? 'Admin' : `Staff ${label.slice(-1)}`} – ${org.hos_name || org.bank_name}`.slice(0, 80),
    role,
    status: 'ACTIVE',
  });
  await Staff.create({
    u_id: user._id,
    role,
    department,
    licence_id: `ORG-${crypto.randomBytes(5).toString('hex').toUpperCase()}`,
    hos_or_bank_id: org._id,
    hos_or_bank_type: orgType,
    created_by: creator,
  });
  return { email, password: plain, role };
}

async function main() {
  if (!(await connectDB())) process.exit(1);
  const master = await Admin.findOne({ email: 'admin@lifevault.org' }) || await Admin.findOne({});
  const sections = [];
  const orgs = [
    ...(await Hospital.find().sort({ hos_name: 1 })).map((o, i) => ({ org: o, orgType: 'Hospital', code: `hosp${String(i + 1).padStart(2, '0')}` })),
    ...(await BloodBank.find().sort({ bank_name: 1 })).map((o, i) => ({ org: o, orgType: 'BloodBank', code: `bank${String(i + 1).padStart(2, '0')}` })),
  ];

  for (const { org, orgType, code } of orgs) {
    const rows = [];
    const admin = await createAccount({ org, orgType, code, label: 'admin', role: 'ORG_ADMIN', department: 'Administration', creator: master?._id });
    if (admin) rows.push(admin);
    const adminUser = await User.findOne({ email: `${code}.admin@lifevault.org` });
    for (const [n, role] of [[1, 'PHLEBOTOMIST'], [2, 'NURSE']]) {
      const row = await createAccount({ org, orgType, code, label: `staff${n}`, role, department: 'Blood Services', creator: adminUser?._id });
      if (row) rows.push(row);
    }
    if (rows.length) sections.push({ name: org.hos_name || org.bank_name, orgType, rows });
  }

  if (sections.length) {
    const lines = [
      '# LifeVault – Organization Login Credentials',
      '',
      '> Generated by `npm run seed-org-accounts`. **Development credentials – do not commit or share.**',
      '> Passwords are stored hashed; change them after first login.',
      '',
      '## Master admin',
      '',
      '| Email | Password |',
      '|---|---|',
      '| admin@lifevault.org | LifeVaultAdmin2026! |',
      '',
      'Master admin creates organizations and their admins. Organization admins create and manage staff. Staff cannot create accounts.',
      '',
    ];
    for (const type of ['Hospital', 'BloodBank']) {
      lines.push(type === 'Hospital' ? '## Hospitals' : '## Blood banks', '');
      for (const s of sections.filter((x) => x.orgType === type)) {
        lines.push(`### ${s.name}`, '', '| Role | Email | Password |', '|---|---|---|');
        for (const r of s.rows) lines.push(`| ${r.role === 'ORG_ADMIN' ? 'Admin' : r.role} | ${r.email} | \`${r.password}\` |`);
        lines.push('');
      }
    }
    fs.writeFileSync(OUT, lines.join('\n'));
  }
  const accounts = sections.reduce((n, s) => n + s.rows.length, 0);
  console.log(`Organizations: ${orgs.length} | accounts created: ${accounts}${accounts ? ' | credentials -> CREDENTIALS.md' : ''}`);
  process.exit(0);
}

main().catch((e) => { console.error(e); process.exit(1); });
